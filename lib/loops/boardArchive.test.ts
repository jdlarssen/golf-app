const noLeaks = () => [];

// Fixtur-adressene i denne fila MÅ stå på repoets allowlist: pre-commit-vakta
// (#1929) nekter alt annet, og repoet er offentlig. For å se skanneren slå til
// kjøres den derfor også mot en snevrere allowlist i en temp-rot, der
// example.com ikke er tillatt. Skanneren og regelen er de samme.
const LEAK = 'ola@example.com';
const STRICT_ROOT = fs.mkdtempSync(path.join(os.tmpdir(), 'tavle-arkiv-'));
fs.mkdirSync(path.join(STRICT_ROOT, '.githooks'));
fs.writeFileSync(path.join(STRICT_ROOT, '.githooks/email-allowlist.txt'), '^noreply@\n');
afterAll(() => fs.rmSync(STRICT_ROOT, { recursive: true, force: true }));
const scanRepo = (text: string) => scanEmailLeaks(text, { script: SCAN_SCRIPT, root: ROOT });
const scan = (text: string) => scanEmailLeaks(text, { script: SCAN_SCRIPT, root: STRICT_ROOT });

const [LOOP_DRIFT, UTROPEREN] = BOARDS;

function live(entry: ArchivedEntry, id: number, body = entry.body): LiveComment {
  return { ...entry, body, id, htmlUrl: `https://github.com/x/y/issues/1110#issuecomment-${id}` };
}

// ── Arkivformatet: de fire håndlagde filene på main er fasiten ───────────────

describe('parseArchive mot de ekte arkivfilene', () => {
  // Tallene er filenes egne «N kommentarer». En løs `^## `-parser gir 97 i
  // juli-1110, fordi en forge-kontrakt i en kommentar har egne ##-overskrifter.
  it.each([
    ['2026-07-loop-drift-1110.md', 89],
    ['2026-07-utroperen-1208.md', 8],
    ['2026-08-loop-drift-1110.md', 82],
    ['2026-08-utroperen-1208.md', 11],
  ])('%s gir %i oppføringer', (file, count) => {
    expect(parseArchive(read(`docs/loops/logg/${file}`))).toHaveLength(count);
  });

  it('tåler bot-logins med klammer', () => {
    const logins = new Set(
      parseArchive(read('docs/loops/logg/2026-08-loop-drift-1110.md')).map((e) => e.login),
    );
    expect(logins).toContain('claude[bot]');
    expect(logins).toContain('github-actions[bot]');
  });

  it('renderArchive gjenskaper august-fila for #1208 byte for byte', () => {
    const file = read('docs/loops/logg/2026-08-utroperen-1208.md');
    expect(
      renderArchive({ board: UTROPEREN, month: '2026-08', entries: parseArchive(file), masked: [] }),
    ).toBe(file);
  });

  // Headerne i de tre andre har håndskrevne tillegg (etterfylling, maskering),
  // men oppføringsdelen skal være identisk.
  it.each([
    [LOOP_DRIFT, '2026-07', '2026-07-loop-drift-1110.md'],
    [UTROPEREN, '2026-07', '2026-07-utroperen-1208.md'],
    [LOOP_DRIFT, '2026-08', '2026-08-loop-drift-1110.md'],
  ])('oppføringsdelen av %s %s rendres identisk', (board, month, file) => {
    const md = read(`docs/loops/logg/${file}`);
    const rendered = renderArchive({ board, month, entries: parseArchive(md), masked: [] });
    const entriesPart = (s: string) => s.slice(s.indexOf('\n---\n\n## '));
    expect(entriesPart(rendered)).toBe(entriesPart(md));
  });
});

describe('renderArchive ↔ parseArchive', () => {
  it('round-tripper bodyer med ---, ## Problem, json-blokk og tom body', () => {
    const entries: ArchivedEntry[] = [
      { login: 'jdlarssen', createdAt: '2026-09-01T02:17:29Z', body: 'Brief\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_' },
      { login: 'claude[bot]', createdAt: '2026-09-02T10:00:00Z', body: '## Problem\n\nTekst\n\n## Design\n\n```json\n{"a": 1}\n```' },
      { login: 'github-actions[bot]', createdAt: '2026-09-03T11:00:00Z', body: '' },
      { login: 'jdlarssen', createdAt: '2026-09-04T12:00:00Z', body: '---\n\n---' },
    ];
    const md = renderArchive({ board: LOOP_DRIFT, month: '2026-09', entries, masked: [] });
    expect(parseArchive(md)).toEqual(entries);
  });

  it('skriver maskerings-avviket i headeren, og bare når noe ble maskert', () => {
    const entries: ArchivedEntry[] = [{ login: 'a', createdAt: '2026-09-01T00:00:00Z', body: 'x' }];
    const plain = renderArchive({ board: UTROPEREN, month: '2026-09', entries, masked: [] });
    const masked = renderArchive({
      board: UTROPEREN,
      month: '2026-09',
      entries,
      masked: ['noen [at] ukjent.example-x.com'],
    });
    expect(plain).not.toContain('Eneste avvik');
    expect(masked).toContain('Eneste avvik fra verbatim');
    expect(masked).toContain('«noen [at] ukjent.example-x.com»');
    expect(masked).not.toContain('@');
  });

  it('sier «1 kommentar» i entall', () => {
    const md = renderArchive({
      board: UTROPEREN,
      month: '2026-09',
      entries: [{ login: 'a', createdAt: '2026-09-05T00:00:00Z', body: 'x' }],
      masked: [],
    });
    expect(md).toContain('urørt. 1 kommentar,\nperiode 2026-09-05 – 2026-09-05.');
  });
});

