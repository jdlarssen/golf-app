describe('e-postmaskering (#1929)', () => {
  it('scan-emails.sh finner en adresse utenfor allowlista, og respekterer den', () => {
    expect(scan(`Skriv til ${LEAK} i dag\n`)).toEqual([LEAK]);
    expect(scan('noreply@example.com\n')).toEqual([]);
    expect(scanRepo(`${LEAK}\n`)).toEqual([]);
  });

  it('maskLeaks gjør adressen om til «[at]»-formen', () => {
    expect(maskLeaks(`skrivefeil: ${LEAK}`, [LEAK])).toEqual({
      text: 'skrivefeil: ola [at] example.com',
      masked: ['ola [at] example.com'],
    });
  });

  // Arkivfila har bare den maskerte formen. Slette-porten må derfor kjøre samme
  // pipeline på den ferske body-en — ellers blir hver maskert kommentar et evig
  // avvik som aldri slettes.
  it.each([
    ['LF', `Hei\nskrivefeil: ${LEAK}\n`],
    ['CRLF', `Hei\r\nskrivefeil: ${LEAK}\r\n`],
  ])('maskert kommentar gir match mot sin rå live-body (%s)', (_label, raw) => {
    const comment: LiveComment = {
      id: 1,
      login: 'jdlarssen',
      createdAt: '2026-09-02T08:00:00Z',
      body: raw,
      htmlUrl: 'u',
    };
    const built = buildArchive({ board: LOOP_DRIFT, month: '2026-09', comments: [comment], scan });
    expect(built?.markdown).toContain('ola [at] example.com');
    expect(built?.markdown).not.toContain(LEAK);
    const [archived] = parseArchive(built!.markdown);
    expect(deleteVerdict(archived, { body: raw }, scan)).toBe('match');
  });

  it('buildArchive nekter å returnere en fil som fortsatt ikke er ren', () => {
    const stubborn = () => [LEAK];
    const comment: LiveComment = { id: 1, login: 'a', createdAt: '2026-09-02T08:00:00Z', body: 'x', htmlUrl: 'u' };
    expect(() => buildArchive({ board: LOOP_DRIFT, month: '2026-09', comments: [comment], scan: stubborn })).toThrow(
      /ikke ren/,
    );
  });
});

describe('buildArchive', () => {
  const c = (id: number, createdAt: string): LiveComment => ({
    id,
    login: 'jdlarssen',
    createdAt,
    body: `kommentar ${id}`,
    htmlUrl: 'u',
  });

  it('tar kun månedens kommentarer, sortert på tid', () => {
    const built = buildArchive({
      board: LOOP_DRIFT,
      month: '2026-09',
      comments: [c(3, '2026-09-30T23:59:59Z'), c(1, '2026-08-31T23:59:59Z'), c(2, '2026-09-01T00:00:00Z'), c(4, '2026-10-01T00:00:00Z')],
      scan: noLeaks,
    });
    expect(built?.entries.map((e) => e.body)).toEqual(['kommentar 2', 'kommentar 3']);
  });

  // En body med en linje på overskriftsformen ville gitt en fil som ikke leses
  // tilbake likt — da skal ingenting skrives, i stedet for en fil slette-fasen
  // senere kvelner på.
  it('nekter å skrive en fil som ikke parses tilbake til de samme oppføringene', () => {
    const tricky = { ...c(1, '2026-09-02T00:00:00Z'), body: 'sitat:\n\n## jdlarssen · 2026-08-01T00:00:00Z\n\nhei' };
    expect(() => buildArchive({ board: LOOP_DRIFT, month: '2026-09', comments: [tricky], scan: noLeaks })).toThrow(
      /leses ikke tilbake/,
    );
  });

  it('gir null når måneden er tom', () => {
    expect(buildArchive({ board: LOOP_DRIFT, month: '2026-09', comments: [], scan: noLeaks })).toBeNull();
  });
});

// ── Planlegging: hvilke måneder arkiveres ─────────────────────────────────────

describe('planArchive', () => {
  const now = new Date('2026-10-01T04:10:00Z');
  const comment = (createdAt: string): LiveComment => ({ id: 1, login: 'a', createdAt, body: 'x', htmlUrl: 'u' });
  const comments = {
    1110: [comment('2026-09-05T00:00:00Z'), comment('2026-10-01T02:00:00Z')],
    1208: [comment('2026-09-06T00:00:00Z')],
  };

  it('uten --month: kun måneder før inneværende, begge tavler', () => {
    const plan = planArchive({ comments, now, dryRun: false, exists: () => false });
    expect(plan.work.map((w) => `${w.month} #${w.board.issue}`)).toEqual(['2026-09 #1110', '2026-09 #1208']);
  });

  it('måned som alt har arkivfil er en no-op med tydelig logglinje', () => {
    const plan = planArchive({ comments, now, month: '2026-09', dryRun: false, exists: () => true });
    expect(plan.work).toEqual([]);
    expect(plan.log).toEqual([
      '2026-09 #1110: fil finnes — hopper over.',
      '2026-09 #1208: fil finnes — hopper over.',
    ]);
  });

  it('tom tavle gir logglinje, den andre arkiveres', () => {
    const plan = planArchive({ comments: { 1110: comments[1110], 1208: [] }, now, dryRun: false, exists: () => false });
    expect(plan.work.map((w) => w.board.issue)).toEqual([1110]);
    expect(plan.log).toContain('2026-09 #1208: ingen kommentarer — ingen fil.');
  });

  it('ekte modus nekter inneværende måned; dry-run tillater den', () => {
    expect(() => planArchive({ comments, now, month: '2026-10', dryRun: false, exists: () => false })).toThrow(
      /inneværende/,
    );
    const plan = planArchive({ comments, now, month: '2026-10', dryRun: true, exists: () => false });
    expect(plan.work.map((w) => w.board.issue)).toEqual([1110]);
  });

  it('ingen gamle kommentarer gir én logglinje og ingen arbeid', () => {
    const plan = planArchive({ comments: { 1110: [], 1208: [] }, now, dryRun: false, exists: () => false });
    expect(plan.work).toEqual([]);
    expect(plan.log).toEqual(['ingen kommentarer før 2026-10 — ingenting å arkivere.']);
  });
});

